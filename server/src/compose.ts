import yaml from "js-yaml";
import { SERVICES, getService, type ServiceDef } from "./catalog.js";
import {
  getSetting,
  getServiceRow,
  listServiceRows,
  randomSecret,
  setSetting,
} from "./db.js";

export const PROJECT_NAME = "staffup";

export interface GlobalConfig {
  domain: string;
  acmeEmail: string;
  adminEmail: string;
  timezone: string;
  [key: string]: string;
}

export function getGlobalConfig(): GlobalConfig {
  const raw = getSetting("global");
  if (raw) return JSON.parse(raw);
  return { domain: "", acmeEmail: "", adminEmail: "", timezone: "UTC" };
}

export function saveGlobalConfig(cfg: Partial<GlobalConfig>) {
  const merged = { ...getGlobalConfig(), ...cfg };
  setSetting("global", JSON.stringify(merged));
  return merged;
}

function ensureSecretSetting(key: string): string {
  const v = getSetting(key);
  if (v) return v;
  const nv = randomSecret();
  setSetting(key, nv);
  return nv;
}

function pgPassword(): string {
  return ensureSecretSetting("pg_password");
}

function serviceConfig(id: string): Record<string, string> {
  const row = getServiceRow(id);
  if (!row) return {};
  return JSON.parse(row.config);
}

function enabledIds(): string[] {
  const rows = listServiceRows().filter((r) => r.enabled === 1);
  return rows.map((r) => r.id);
}

function serviceEnv(def: ServiceDef, global: GlobalConfig): Record<string, string> {
  const env: Record<string, string> = {};
  const cfg = serviceConfig(def.id);
  for (const f of def.fields ?? []) {
    if (f.type === "boolean") continue;
    const v = cfg[f.key] ?? "";
    if (v !== "") env[f.key] = v;
  }
  for (const g of def.globalEnv ?? []) {
    switch (g.from) {
      case "PG_HOST_LITERAL":
        env[g.key] = "postgres";
        break;
      case "PG_USER":
        env[g.key] = cfg["PG_USER"] || "staffup";
        break;
      case "PG_PASSWORD":
        env[g.key] = pgPassword();
        break;
      case "PG_DATABASE":
        env[g.key] = `${def.id.replace(/-/g, "_")}_db`;
        break;
      case "PG_HOST":
        env[g.key] = "postgres";
        break;
      default:
        env[g.key] = cfg[g.from] ?? "";
    }
  }
  for (const [k, v] of Object.entries(def.extraEnv ?? {})) {
    env[k] = v.replace(/\$\{(\w+)\}/g, (_, name) => {
      if (name === "DOMAIN") return global.domain;
      return cfg[name] ?? "";
    });
  }
  return env;
}

/** Generate the top-level .env content consumed by the generated compose file. */
export function generateEnv(): string {
  const global = getGlobalConfig();
  const lines: string[] = [
    "# Generated by Staff Up — do not edit by hand",
    `DOMAIN=${global.domain}`,
    `ACME_EMAIL=${global.acmeEmail}`,
    `TZ=${global.timezone}`,
    `STAFFUP_LABEL_PREFIX=staffup`,
  ];
  for (const def of SERVICES) {
    const ids = enabledIds();
    if (!ids.includes(def.id)) continue;
    const env = serviceEnv(def, global);
    for (const [k, v] of Object.entries(env)) {
      lines.push(`${def.id.toUpperCase().replace(/-/g, "_")}__${k}=${v}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

export interface ComposeSpec {
  services: Record<string, any>;
  networks: Record<string, any>;
  volumes: Record<string, any>;
}

export function generateCompose(): { compose: ComposeSpec; env: Record<string, string> } {
  const global = getGlobalConfig();
  const enabled = enabledIds();
  const services: Record<string, any> = {};
  const volumes: Record<string, any> = {};
  const envOut: Record<string, string> = {};

  // Traefik edge network
  services["traefik"] = {
    image: "traefik:v3.3",
    command: [
      "--providers.docker=true",
      "--providers.docker.exposedbydefault=false",
      "--providers.docker.network=proxy",
      "--entrypoints.web.address=:80",
      "--entrypoints.websecure.address=:443",
      "--entrypoints.web.http.redirections.entrypoint.to=websecure",
      "--entrypoints.web.http.redirections.entrypoint.scheme=https",
      `--certificatesresolvers.le.acme.email=${global.acmeEmail || getSetting("acme_email") || ""}`,
      "--certificatesresolvers.le.acme.storage=/letsencrypt/acme.json",
      "--certificatesresolvers.le.acme.httpchallenge=true",
      "--certificatesresolvers.le.acme.httpchallenge.entrypoint=web",
      "--api.dashboard=false",
    ],
    ports: ["80:80", "443:443"],
    volumes: ["traefik-data:/letsencrypt", "/var/run/docker.sock:/var/run/docker.sock:ro"],
    networks: ["proxy"],
    restart: "unless-stopped",
    labels: { "staffup.managed": "true" },
  };

  const pgSecret = pgPassword();
  if (enabled.includes("postgres")) {
    services["postgres"] = {
      image: "postgres:17-alpine",
      environment: {
        POSTGRES_USER: "staffup",
        POSTGRES_PASSWORD: pgSecret,
        POSTGRES_DB: "staffup",
        TZ: global.timezone || "UTC",
      },
      volumes: ["postgres-data:/var/lib/postgresql/data"],
      networks: ["internal"],
      restart: "unless-stopped",
      labels: { "staffup.managed": "true" },
      healthcheck: {
        test: ["CMD-SHELL", "pg_isready -U staffup"],
        interval: "10s",
        timeout: "5s",
        retries: 5,
      },
    };
  }

  if (enabled.includes("redis")) {
    services["redis"] = {
      image: "redis:7-alpine",
      command: ["redis-server", "--save", "60", "1", "--loglevel", "warning"],
      volumes: ["redis-data:/data"],
      networks: ["internal"],
      restart: "unless-stopped",
      labels: { "staffup.managed": "true" },
    };
  }

  for (const def of SERVICES) {
    if (def.id === "traefik" || def.id === "postgres" || def.id === "redis") continue;
    if (!enabled.includes(def.id)) continue;
    if (def.configOnly) continue;

    const svc: any = {
      image: def.image,
      restart: "unless-stopped",
      labels: { "staffup.managed": "true" },
      environment: {} as Record<string, string>,
      networks: ["internal"],
    };
    const env = serviceEnv(def, global);
    svc.environment = Object.fromEntries(
      Object.entries(env).map(([k, v]) => [k, String(v).replaceAll("$", "$$")])
    );
    for (const [k, v] of Object.entries(env)) envOut[`${def.id}_${k}`] = v;

    if (def.volumes) svc.volumes = def.volumes;
    if (def.command) svc.command = def.command;
    if (def.dependsOn) svc.depends_on = def.dependsOn.filter((d) => enabled.includes(d));

    if (def.subdomain && def.port) {
      const rule = `Host(\`${def.subdomain}.${global.domain}\`)`;
      svc.networks = ["internal", "proxy"];
      svc.labels = {
        ...svc.labels,
        "traefik.enable": "true",
        [`traefik.http.routers.${def.id}.rule`]: rule,
        [`traefik.http.routers.${def.id}.entrypoints`]: "websecure",
        [`traefik.http.routers.${def.id}.tls`]: "true",
        [`traefik.http.routers.${def.id}.tls.certresolver`]: "le",
        [`traefik.http.services.${def.id}.loadbalancer.server.port`]: String(def.port),
      };
    }
    services[def.id] = svc;
  }

  for (const def of SERVICES) {
    if (def.volumes) {
      for (const v of def.volumes) {
        const name = v.split(":")[0];
        if (!name.startsWith("/")) volumes[name] = {};
      }
    }
  }

  return {
    compose: {
      services,
      networks: {
        proxy: { name: `${PROJECT_NAME}_proxy`, driver: "bridge" },
        // outbound access needed: Hermes -> LLM APIs, Authentik/Mattermost -> email, Tailscale -> DERP
        internal: { name: `${PROJECT_NAME}_internal`, driver: "bridge" },
      },
      volumes,
    },
    env: envOut,
  };
}

export function composeYaml(): string {
  const { compose } = generateCompose();
  return yaml.dump(compose, { lineWidth: 120, noRefs: true });
}

/** Validate required fields before allowing a deploy. Returns missing list. */
export function validateConfig(): { ok: boolean; missing: string[] } {
  const global = getGlobalConfig();
  const missing: string[] = [];
  if (!global.domain) missing.push("Domain name");
  if (!global.acmeEmail) missing.push("Let's Encrypt email");
  for (const id of enabledIds()) {
    const def = getService(id);
    if (!def) continue;
    const cfg = serviceConfig(id);
    for (const f of def.fields ?? []) {
      if (f.required && !cfg[f.key]) {
        missing.push(`${def.name}: ${f.label}`);
      }
    }
  }
  return { ok: missing.length === 0, missing };
}